CREATE TABLE IF NOT EXISTS display_screens (
 id CHAR(36) NOT NULL PRIMARY KEY,
 tenant_id VARCHAR(36) NOT NULL,
 branch_id VARCHAR(36) NULL,
 name VARCHAR(120) NOT NULL,
 token_hash CHAR(64) NOT NULL,
 refresh_seconds INT NOT NULL DEFAULT 15,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 paused BOOLEAN NOT NULL DEFAULT FALSE,
 qr_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 qr_position ENUM('top-left','top-right','bottom-left','bottom-right','center') NOT NULL DEFAULT 'bottom-right',
 qr_size INT NOT NULL DEFAULT 140,
 qr_foreground VARCHAR(20) NOT NULL DEFAULT '#111827',
 qr_background VARCHAR(20) NOT NULL DEFAULT '#ffffff',
 display_layout ENUM('single','double','triple','quad','split') NOT NULL DEFAULT 'single',
 created_by VARCHAR(36) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 last_seen_at DATETIME NULL,
 UNIQUE KEY display_screens_token_hash_uq (token_hash),
 KEY display_screens_tenant_branch_idx (tenant_id, branch_id, enabled),
 CONSTRAINT display_screens_tenant_fk FOREIGN KEY (tenant_id) REFERENCES tenants(id),
 CONSTRAINT display_screens_branch_fk FOREIGN KEY (branch_id) REFERENCES branches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS display_slides (
 id CHAR(36) NOT NULL PRIMARY KEY,
 screen_id CHAR(36) NOT NULL,
 tenant_id VARCHAR(36) NOT NULL,
 media_url VARCHAR(500) NULL,
 external_video_url VARCHAR(700) NULL,
 video_loop BOOLEAN NOT NULL DEFAULT TRUE,
 transition_effect ENUM('fade','zoom','slide','kenburns') NOT NULL DEFAULT 'fade',
 badge_text VARCHAR(64) NULL,
 title_ar VARCHAR(180) NULL,
 title_en VARCHAR(180) NULL,
 title_fr VARCHAR(180) NULL,
 subtitle_ar VARCHAR(500) NULL,
 subtitle_en VARCHAR(500) NULL,
 subtitle_fr VARCHAR(500) NULL,
 duration_seconds INT NOT NULL DEFAULT 10,
 sort_order INT NOT NULL DEFAULT 0,
 starts_at DATETIME NULL,
 ends_at DATETIME NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY display_slides_screen_order_idx (screen_id, enabled, sort_order),
 KEY display_slides_tenant_idx (tenant_id),
 CONSTRAINT display_slides_screen_fk FOREIGN KEY (screen_id) REFERENCES display_screens(id) ON DELETE CASCADE,
 CONSTRAINT display_slides_tenant_fk FOREIGN KEY (tenant_id) REFERENCES tenants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;